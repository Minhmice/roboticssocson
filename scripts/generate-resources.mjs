import fs from "node:fs";
import path from "node:path";
import { RESOURCE_CATEGORIES, RESOURCE_ARTICLES } from "../src/data/resources.ts";
import { parseMdxContent } from "../src/lib/resources/parser.ts";
import { validateResources } from "./check-resources.mjs";

const ROOT_DIR = process.cwd();
const CONTENT_DIR = path.join(ROOT_DIR, "src", "content", "resources");
const MANIFEST_FILE = path.join(ROOT_DIR, "src", "lib", "resources", "manifest.generated.ts");
const PUBLIC_RESOURCES_DIR = path.join(ROOT_DIR, "public", "resources");
const MANUAL_SEARCH_FILE = path.join(ROOT_DIR, "public", "manual", "search-index.json");

console.log("[generate-resources] Validating and building resources pipeline...");

// 1. Shared validation check
const { errors } = validateResources({ contentDir: CONTENT_DIR });
if (errors.length > 0) {
  for (const err of errors) console.error(err);
  console.error(`[generate-resources] Aborting: ${errors.length} validation errors encountered.`);
  process.exit(1);
}

// 2. Generate static import manifest
const readyArticles = RESOURCE_ARTICLES.filter((a) => a.status === "ready");
const importLines = [];
const manifestEntries = [];

for (const art of readyArticles) {
  const catId = art.categoryId;
  const slug = art.slug;
  const safeVarPrefix = `Article_${catId.replace(/[^a-zA-Z0-9]/g, "_")}_${slug.replace(/[^a-zA-Z0-9]/g, "_")}`;

  importLines.push(`import ${safeVarPrefix}_vi from "@/content/resources/${catId}/${slug}.vi.mdx";`);
  importLines.push(`import ${safeVarPrefix}_en from "@/content/resources/${catId}/${slug}.en.mdx";`);

  manifestEntries.push(`  "${catId}/${slug}": {\n    vi: ${safeVarPrefix}_vi,\n    en: ${safeVarPrefix}_en,\n  },`);
}

const manifestContent = `// GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-resources.mjs
import type { ComponentType } from "react";
import type { Locale } from "@/lib/i18n/locales";

export type MDXArticleComponent = ComponentType<{
  components?: Record<string, ComponentType<unknown>>;
}>;

${importLines.join("\n")}

export const RESOURCE_MANIFEST: Record<
  string,
  Partial<Record<Locale, MDXArticleComponent>>
> = {
${manifestEntries.join("\n")}
};
`;

fs.writeFileSync(MANIFEST_FILE, manifestContent, "utf8");
console.log(`[generate-resources] Written manifest with ${readyArticles.length} ready articles.`);

// 3. Generate search indices
if (!fs.existsSync(PUBLIC_RESOURCES_DIR)) {
  fs.mkdirSync(PUBLIC_RESOURCES_DIR, { recursive: true });
}

let manualSearchData = { heads: [], items: [] };
if (fs.existsSync(MANUAL_SEARCH_FILE)) {
  try {
    manualSearchData = JSON.parse(fs.readFileSync(MANUAL_SEARCH_FILE, "utf8"));
  } catch (err) {
    console.warn(`[generate-resources] Warning: failed to parse manual search index:`, err);
  }
}

for (const locale of ["vi", "en"]) {
  const docs = [];

  // A. Category destinations (exclude programming)
  for (const cat of RESOURCE_CATEGORIES) {
    if (cat.id === "programming") continue;

    const isRules = cat.id === "rules";
    const hasReadyArticle = RESOURCE_ARTICLES.some(
      (a) => a.categoryId === cat.id && a.status === "ready",
    );
    const isCategoryReady = isRules || hasReadyArticle;

    docs.push({
      id: `category:${cat.id}`,
      categoryId: cat.id,
      title: cat.title[locale] ?? cat.title.vi,
      description: cat.description[locale] ?? cat.description.vi,
      href: isRules ? "/ftc-rules" : `/resources/${cat.id}`,
      status: isCategoryReady ? "ready" : "soon",
      tags: isRules ? ["Rules", "FTC", "Manual"] : ["FTC", "Resources"],
      body: "",
      headings: "",
    });
  }

  // B. Article metadata & MDX content (exclude programming)
  for (const art of RESOURCE_ARTICLES) {
    if (art.categoryId === "programming") continue;

    let body = "";
    let headings = "";

    if (art.status === "ready") {
      const filePath = path.join(CONTENT_DIR, art.categoryId, `${art.slug}.${locale}.mdx`);
      if (fs.existsSync(filePath)) {
        const source = fs.readFileSync(filePath, "utf8");
        const parsed = parseMdxContent(source);
        body = parsed.body;
        headings = parsed.headings;
      }
    }

    docs.push({
      id: `${art.categoryId}/${art.slug}`,
      categoryId: art.categoryId,
      title: art.title[locale] ?? art.title.vi,
      description: art.summary[locale] ?? art.summary.vi,
      href: `/resources/${art.categoryId}/${art.slug}`,
      status: art.status,
      tags: art.tags,
      body,
      headings,
    });
  }

  // C. Manual headings & rules (included under rules category)
  for (const [, anchor, head, vi, en, kind] of manualSearchData.items) {
    if (kind === "r") {
      docs.push({
        id: `manual:rule:${anchor}`,
        categoryId: "rules",
        title: locale === "vi" ? `Luật ${anchor}` : `Rule ${anchor}`,
        description: locale === "vi" ? vi : en,
        href: `/ftc-rules#${anchor}`,
        status: "ready",
        tags: ["Rules", "FTC", "Manual", anchor],
        body: locale === "vi" ? vi : en,
        headings: manualSearchData.heads[head] || "",
      });
    } else if (kind === "h") {
      docs.push({
        id: `manual:heading:${anchor}`,
        categoryId: "rules",
        title: locale === "vi" ? vi : en,
        description: locale === "vi" ? vi : en,
        href: `/ftc-rules#${anchor}`,
        status: "ready",
        tags: ["Rules", "Manual"],
        body: "",
        headings: manualSearchData.heads[head] || (locale === "vi" ? vi : en),
      });
    }
  }

  const outPath = path.join(PUBLIC_RESOURCES_DIR, `search-index.${locale}.json`);
  fs.writeFileSync(outPath, JSON.stringify(docs, null, 2), "utf8");
  console.log(`[generate-resources] Generated ${docs.length} documents for ${locale} at ${outPath}`);
}

console.log("[generate-resources] Resource generation finished successfully.");
